function labelOf(name: string): string {
  return name.split('-').map((word) => word.charAt(0).toUpperCase() + word.slice(1)).join(' ')
}

const LIGHT_NAMES = [
  'ayu-light',
  'light',
  'catppuccin-latte',
  'everforest-light',
  'graphite',
  'gruvbox-light',
  'rose-pine-dawn',
  'solarized-light',
  'tokyo-night-light',
  'ulysses'
]

const DARK_NAMES = [...DARK].sort()

export const themes: ThemeChoice[] = [
  ...LIGHT_NAMES.map((name) => ({ name, label: labelOf(name), dark: false })),
  ...DARK_NAMES.map((name) => ({ name, label: labelOf(name), dark: true }))
]

export const themeNames: readonly string[] = themes.map((theme) => theme.name)

export function applyTheme(name: string): void {
  const style = sheet('theme-style')
  const css = CSS[name]
  style.textContent = css ? `@media not print {\n${css}\n}` : ''
  document.documentElement.classList.toggle('dark', DARK.has(name))
}

export function applyEditorWidth(value: string): void {
  const style = sheet('editor-width')
  const width = /^[0-9]+(?:ch|px|%)$/.test(value) ? value : ''
  style.textContent = width
    ? `:root { --editorAreaWidth: calc(100px + ${width}); --editor-area-width: calc(100px + ${width}); }`
    : ''
}

function sheet(id: string): HTMLStyleElement {
  const existing = document.getElementById(id)
  if (existing instanceof HTMLStyleElement) return existing
  const created = document.createElement('style')
  created.id = id
  document.head.appendChild(created)
  return created
}
